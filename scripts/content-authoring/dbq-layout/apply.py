"""Puts every document of every DBQ prompt on its own lines: label, Source, and the quotation as a blockquote.

Written as `**Document 1**\\nSource: ...\\n"quote"` (three consecutive lines), markdown joined them into one paragraph:
"Document 1 Source: ... "quote"". Now:

    **Document 1**

    Source: ...

    > "quote"

The blockquote is the same treatment the multiple-choice passages get, so a source reads as a source. The rewrite is
idempotent (it only matches the old three-line form), changes nothing but those line breaks (checked below by undoing it),
and edits the file as raw text so a hand-formatted pool (World History's) is not reformatted. U.S. History's pool is
generated by ap-us-history/pool.py, whose docs() helper emits the new layout; running this over it is a no-op.

Usage: python3 apply.py [--check]     (--check changes nothing and exits 1 if any prompt is still in the old layout)
"""
import json, os, re, sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "../../../content"))
COURSES = ["ap-world", "ap-us-history"]
OLD = re.compile(r'\*\*Document (\d+)\*\*\nSource: ([^\n]*)\n("[^\n]*)')
NEW = re.compile(r'\*\*Document (\d+)\*\*\n\nSource: ([^\n]*)\n\n> ("[^\n]*)')


def relayout(prompt):
    return OLD.sub(lambda m: f"**Document {m[1]}**\n\nSource: {m[2]}\n\n> {m[3]}", prompt)


def undo(prompt):
    return NEW.sub(lambda m: f"**Document {m[1]}**\nSource: {m[2]}\n{m[3]}", prompt)


def main():
    check = "--check" in sys.argv
    pending = 0
    for course in COURSES:
        path = f"{ROOT}/{course}/frqs/dbq-leq-pool.json"
        raw = open(path, encoding="utf-8").read()
        for item in json.loads(raw):
            if item.get("type") != "DBQ":
                continue
            old = item["prompt"]
            new = relayout(old)
            if new == old:
                assert len(NEW.findall(old)) == 7 and not OLD.search(old), f"{item['id']}: unexpected document layout"
                continue
            pending += 1
            assert len(OLD.findall(old)) == 7, f"{item['id']}: expected 7 documents, found {len(OLD.findall(old))}"
            assert undo(new) == old, f"{item['id']}: the rewrite changed more than line breaks"
            assert len(NEW.findall(new)) == 7 and not OLD.search(new)
            if check:
                print(f"{course} {item['id']}: old layout")
                continue
            for ascii_only in (False, True):
                a, b = json.dumps(old, ensure_ascii=ascii_only), json.dumps(new, ensure_ascii=ascii_only)
                if raw.count(a) == 1:
                    raw = raw.replace(a, b)
                    break
            else:
                raise SystemExit(f"{course} {item['id']}: could not find the prompt exactly once in the file")
            print(f"{course} {item['id']}: 7 documents re-laid out")
        if not check:
            open(path, "w", encoding="utf-8").write(raw)
    print("still in the old layout:" if check else "re-laid out this run:", pending)
    sys.exit(1 if (check and pending) else 0)


main()
